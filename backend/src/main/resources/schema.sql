DROP TABLE IF EXISTS appeals;
DROP TABLE IF EXISTS llm_call_logs;
DROP TABLE IF EXISTS judge_jobs;
DROP TABLE IF EXISTS submissions;
DROP TABLE IF EXISTS lab_constraints;
DROP TABLE IF EXISTS lab_tests;
DROP TABLE IF EXISTS publication_audit;
DROP TABLE IF EXISTS published_marks;
DROP TABLE IF EXISTS publications;
DROP TABLE IF EXISTS review_items;
DROP TABLE IF EXISTS counted_submissions;
DROP TABLE IF EXISTS ta_classes;
DROP TABLE IF EXISTS labs;
DROP TABLE IF EXISTS class_members;
DROP TABLE IF EXISTS classes;
DROP TABLE IF EXISTS oauth_accounts;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    id            UUID         PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    full_name     VARCHAR(150),
    avatar_url    TEXT,
    role          VARCHAR(16)  NOT NULL DEFAULT 'student' CHECK (role IN ('admin', 'ta', 'student')),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE oauth_accounts (
    id               UUID         PRIMARY KEY,
    user_id          UUID         NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider         VARCHAR(32)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_oauth_provider_user UNIQUE (provider, provider_user_id)
);

CREATE TABLE classes (
    id         INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64)  NOT NULL UNIQUE,
    name       VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE class_members (
    class_id    INT         NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    user_id     UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    member_role VARCHAR(16) NOT NULL CHECK (member_role IN ('ta', 'student')),
    PRIMARY KEY (class_id, user_id)
);

CREATE TABLE labs (
    id           INT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    class_id     INT            NOT NULL,
    deadline     VARCHAR(64)    NOT NULL,
    title        VARCHAR(200)   NOT NULL DEFAULT '',
    statement_md TEXT           NOT NULL DEFAULT '',
    cost_cap_usd NUMERIC(10, 4) NOT NULL DEFAULT 5.0000,
    created_by   UUID           NULL REFERENCES users(id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ta_classes (
    ta_id    VARCHAR(64) NOT NULL,
    class_id INT         NOT NULL,
    PRIMARY KEY (ta_id, class_id)
);

CREATE TABLE lab_tests (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id          INT          NOT NULL REFERENCES labs(id) ON DELETE CASCADE,
    name            VARCHAR(120) NOT NULL,
    input_data      TEXT         NOT NULL DEFAULT '',
    expected_output TEXT         NOT NULL DEFAULT '',
    time_limit_ms   INT          NOT NULL DEFAULT 2000 CHECK (time_limit_ms > 0),
    memory_limit_mb INT          NOT NULL DEFAULT 256  CHECK (memory_limit_mb > 0),
    is_sample       BOOLEAN      NOT NULL DEFAULT FALSE,
    order_index     INT          NOT NULL DEFAULT 0
);

CREATE TABLE lab_constraints (
    lab_id           INT         NOT NULL REFERENCES labs(id) ON DELETE CASCADE,
    constraint_id    VARCHAR(64) NOT NULL,
    constraint_type  VARCHAR(16) NOT NULL CHECK (constraint_type IN ('hard', 'semantic')),
    description      TEXT        NOT NULL,
    deduction_tenths INT         NOT NULL CHECK (deduction_tenths BETWEEN 0 AND 100),
    PRIMARY KEY (lab_id, constraint_id)
);

CREATE TABLE counted_submissions (
    id           INT         PRIMARY KEY,
    lab_id       INT         NOT NULL REFERENCES labs(id),
    student_id   VARCHAR(64) NOT NULL,
    judge_status VARCHAR(32) NOT NULL CHECK (judge_status IN ('queued', 'running', 'AC', 'WA', 'TLE', 'MLE', 'RE', 'CE')),
    score_tenths INT         NOT NULL CHECK (score_tenths BETWEEN 0 AND 100),
    UNIQUE (lab_id, student_id)
);

CREATE TABLE submissions (
    id                INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id            INT          NOT NULL REFERENCES labs(id) ON DELETE CASCADE,
    student_id        UUID         NOT NULL REFERENCES users(id),
    source_code       TEXT         NOT NULL,
    stripped_code     TEXT         NULL,
    judge_status      VARCHAR(32)  NOT NULL DEFAULT 'queued'
        CHECK (judge_status IN ('queued', 'running', 'AC', 'WA', 'TLE', 'MLE', 'RE', 'CE')),
    score_tenths      INT          NOT NULL DEFAULT 0 CHECK (score_tenths BETWEEN 0 AND 100),
    passed_tests      INT          NOT NULL DEFAULT 0,
    total_tests       INT          NOT NULL DEFAULT 0,
    execution_time_ms INT          NULL,
    memory_kb         INT          NULL,
    compile_error     TEXT         NULL,
    trace_id          VARCHAR(64)  NOT NULL,
    idempotency_key   VARCHAR(128) NULL,
    submitted_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    judged_at         TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT uq_submissions_idempotency UNIQUE (lab_id, student_id, idempotency_key)
);

CREATE TABLE judge_jobs (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id INT          NOT NULL UNIQUE REFERENCES submissions(id) ON DELETE CASCADE,
    status        VARCHAR(16)  NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'done', 'failed')),
    attempts      INT          NOT NULL DEFAULT 0,
    locked_by     VARCHAR(64)  NULL,
    locked_at     TIMESTAMP WITH TIME ZONE NULL,
    trace_parent  VARCHAR(128) NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at   TIMESTAMP WITH TIME ZONE NULL
);

CREATE TABLE review_items (
    submission_id    INT         NOT NULL REFERENCES counted_submissions(id),
    constraint_id    VARCHAR(64) NOT NULL,
    decision         VARCHAR(32) NULL CHECK (decision IN ('pass', 'violation')),
    verdict          VARCHAR(16) NOT NULL DEFAULT 'unsure' CHECK (verdict IN ('pass', 'violation', 'unsure')),
    source           VARCHAR(16) NOT NULL DEFAULT 'llm' CHECK (source IN ('hard_rule', 'llm', 'guardrail')),
    evidence_json    TEXT        NOT NULL DEFAULT '[]',
    guardrail_reason VARCHAR(64) NULL,
    in_queue         BOOLEAN     NOT NULL DEFAULT TRUE,
    sampled_pass     BOOLEAN     NOT NULL DEFAULT FALSE,
    decided_by       VARCHAR(64) NULL,
    decided_at       TIMESTAMP WITH TIME ZONE NULL,
    PRIMARY KEY (submission_id, constraint_id)
);

CREATE TABLE llm_call_logs (
    id                  BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id       INT            NULL REFERENCES submissions(id) ON DELETE SET NULL,
    lab_id              INT            NULL REFERENCES labs(id) ON DELETE SET NULL,
    constraint_id       VARCHAR(64)    NOT NULL,
    provider            VARCHAR(64)    NOT NULL,
    model               VARCHAR(128)   NOT NULL,
    provider_request_id VARCHAR(128)   NULL,
    prompt_tokens       INT            NOT NULL DEFAULT 0,
    completion_tokens   INT            NOT NULL DEFAULT 0,
    latency_ms          INT            NOT NULL DEFAULT 0,
    cost_usd            NUMERIC(12, 6) NOT NULL DEFAULT 0,
    sanitized_prompt    TEXT           NULL,
    raw_response        TEXT           NULL,
    verdict             VARCHAR(16)    NOT NULL,
    guardrail_reason    VARCHAR(64)    NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE publications (
    lab_id  INT           PRIMARY KEY REFERENCES labs(id),
    receipt VARCHAR(4096) NOT NULL
);

CREATE TABLE published_marks (
    lab_id        INT NOT NULL REFERENCES publications(lab_id),
    submission_id INT NOT NULL REFERENCES counted_submissions(id),
    score_tenths  INT NOT NULL CHECK (score_tenths BETWEEN 0 AND 100),
    PRIMARY KEY (lab_id, submission_id)
);

CREATE TABLE publication_audit (
    lab_id   INT         PRIMARY KEY REFERENCES publications(lab_id),
    actor_id VARCHAR(64) NOT NULL,
    at       VARCHAR(64) NOT NULL,
    event    VARCHAR(64) NOT NULL CHECK (event = 'lab.published')
);

CREATE TABLE appeals (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id          INT         NOT NULL REFERENCES labs(id) ON DELETE CASCADE,
    submission_id   INT         NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    student_id      UUID        NOT NULL REFERENCES users(id),
    constraint_id   VARCHAR(64) NOT NULL,
    reason          TEXT        NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected')),
    decision_reason TEXT        NULL,
    decided_by      UUID        NULL REFERENCES users(id),
    decided_at      TIMESTAMP WITH TIME ZONE NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_appeals_submission_constraint UNIQUE (submission_id, constraint_id)
);
